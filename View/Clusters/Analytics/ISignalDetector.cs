// ==========================================================================
//  ISignalDetector.cs — Контракт детектора паттернов в истории кластеров
// ==========================================================================

namespace QScalp.View.ClustersSpace.Analytics
{
  // ==========================================================================

  interface ISignalDetector
  {
    /// <summary>Имя детектора — идёт в поле Signal.Source и в CSV-лог.</summary>
    string Name { get; }

    /// <summary>Включён ли детектор (пользовательская настройка).</summary>
    bool Enabled { get; }

    /// <summary>
    /// Возвращает сработавший сигнал по текущему состоянию истории, или null.
    /// Детектор должен сам следить за гистерезисом, чтобы не дублировать
    /// сигнал на одном и том же кластере.
    /// </summary>
    Signal Evaluate(ClusterHistory history);
  }

  // ==========================================================================

  interface ISignalSink
  {
    void Emit(Signal signal);
  }

  // ==========================================================================
}
